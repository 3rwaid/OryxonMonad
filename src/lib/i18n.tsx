const dicts: Record<Lang, Dict> = { en, id };

interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function detectDefaultLang(): Lang {
  if (typeof window === 'undefined') return 'en';
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === 'en' || stored === 'id') return stored;
  const nav = navigator.language || (navigator.languages?.[0] ?? '');
  return nav.toLowerCase().startsWith('id') ? 'id' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    setLangState(detectDefaultLang());
  }, []);

  useEffect(() => {
    if (localStorage.getItem(STORAGE_KEY)) return;
    let cancelled = false;
    fetch('https://ipapi.co/json/')
      .then((r) => r.ok ? r.json() : null)
      .then((data) => {
        if (cancelled || !data?.country_code) return;
        const detected: Lang = String(data.country_code).toUpperCase() === 'ID' ? 'id' : 'en';
        if (!localStorage.getItem(STORAGE_KEY)) setLangState(detected);
      })
      .catch(() => {})
      .finally(() => { if (!cancelled) {} });
    return () => { cancelled = true; };
  }, []);

  const setLang = useCallback((l: Lang) => {
    localStorage.setItem(STORAGE_KEY, l);
    setLangState(l);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      let str = dicts[lang][key] ?? dicts.en[key] ?? key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          str = str.replace(`{${k}}`, String(v));
        }
      }
      return str;
    },
    [lang],
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
